const oracledb = require('oracledb');
const bcrypt = require('bcryptjs');

oracledb.outFormat = oracledb.OUT_FORMAT_OBJECT;
oracledb.autoCommit = true;

const dbConfig = {
  user: process.env.DB_USER || 'system',
  password: process.env.DB_PASSWORD || '2003',
  connectString: process.env.DB_CONNECT_STRING || 'localhost:1521/xe'
};

async function initDB() {
  let conn;
  try {
    conn = await oracledb.getConnection(dbConfig);
    console.log('Conectado a Oracle DB para inicializar esquema con trazabilidad de stock...');

    async function dropTableIfExists(tableName) {
      try {
        await conn.execute(`DROP TABLE ${tableName} CASCADE CONSTRAINTS`);
      } catch (err) {
        // Ignorar si no existe
      }
    }

    let recrear = false;
    try {
      await conn.execute(`SELECT stock_anterior FROM movimiento_inventario WHERE ROWNUM = 1`);
    } catch (e) {
      recrear = true;
    }

    if (recrear) {
      console.log('Actualizando esquema de movimiento_inventario...');
      await dropTableIfExists('detalle_venta');
      await dropTableIfExists('venta');
      await dropTableIfExists('movimiento_inventario');
      await dropTableIfExists('producto');
      await dropTableIfExists('categoria');
      await dropTableIfExists('empleado');

      // 1. Tabla EMPLEADO
      await conn.execute(`
        CREATE TABLE empleado (
            id_empleado NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nombre VARCHAR2(100) NOT NULL,
            correo VARCHAR2(100) UNIQUE NOT NULL,
            contrasena VARCHAR2(100) NOT NULL,
            rol VARCHAR2(20) DEFAULT 'USER' NOT NULL,
            estado VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL
        )
      `);

      // 2. Tabla CATEGORIA
      await conn.execute(`
        CREATE TABLE categoria (
            id_categoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nombre_categoria VARCHAR2(100) NOT NULL,
            descripcion VARCHAR2(255)
        )
      `);

      // 3. Tabla PRODUCTO
      await conn.execute(`
        CREATE TABLE producto (
            id_producto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            codigo VARCHAR2(50) UNIQUE NOT NULL,
            nombre VARCHAR2(100) NOT NULL,
            precio_compra NUMBER(10, 2) NOT NULL,
            precio_venta NUMBER(10, 2) NOT NULL,
            stock_actual NUMBER(10, 0) DEFAULT 0 NOT NULL,
            stock_minimo NUMBER(10, 0) DEFAULT 5 NOT NULL,
            id_categoria NUMBER NOT NULL,
            CONSTRAINT fk_producto_categoria FOREIGN KEY (id_categoria) REFERENCES categoria(id_categoria)
        )
      `);

      // 4. Tabla MOVIMIENTO_INVENTARIO (Con trazabilidad de stock_anterior y stock_nuevo)
      await conn.execute(`
        CREATE TABLE movimiento_inventario (
            id_movimiento NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            tipo_movimiento VARCHAR2(20) NOT NULL,
            cantidad NUMBER(10, 0) NOT NULL,
            stock_anterior NUMBER(10, 0) DEFAULT 0 NOT NULL,
            stock_nuevo NUMBER(10, 0) DEFAULT 0 NOT NULL,
            motivo VARCHAR2(255) DEFAULT 'Sin motivo',
            fecha_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            id_producto NUMBER NOT NULL,
            id_empleado NUMBER NOT NULL,
            CONSTRAINT fk_mov_producto FOREIGN KEY (id_producto) REFERENCES producto(id_producto),
            CONSTRAINT fk_mov_empleado FOREIGN KEY (id_empleado) REFERENCES empleado(id_empleado)
        )
      `);

      // 5. Tabla VENTA
      await conn.execute(`
        CREATE TABLE venta (
            id_venta NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            fecha_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            total_recaudado NUMBER(10, 2) NOT NULL,
            id_empleado NUMBER NOT NULL,
            CONSTRAINT fk_venta_empleado FOREIGN KEY (id_empleado) REFERENCES empleado(id_empleado)
        )
      `);

      // 6. Tabla DETALLE_VENTA
      await conn.execute(`
        CREATE TABLE detalle_venta (
            id_detalle NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            id_venta NUMBER NOT NULL,
            id_producto NUMBER NOT NULL,
            cantidad NUMBER(10, 0) NOT NULL,
            precio_unitario NUMBER(10, 2) NOT NULL,
            CONSTRAINT fk_detalle_venta FOREIGN KEY (id_venta) REFERENCES venta(id_venta),
            CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES producto(id_producto)
        )
      `);

      console.log('Tablas con trazabilidad de stock creadas exitosamente.');

      // Insertar Categorías semilla
      const categorias = [
        ['Abarrotes', 'Productos básicos de consumo diario'],
        ['Lácteos', 'Leche, quesos, yogures'],
        ['Limpieza', 'Detergentes y desinfectantes'],
        ['Bebidas', 'Jugos, gaseosas y aguas']
      ];
      for (const cat of categorias) {
        await conn.execute(
          `INSERT INTO categoria (nombre_categoria, descripcion) VALUES (:1, :2)`,
          cat
        );
      }

      // Insertar Empleados por defecto
      const salt = await bcrypt.genSalt(10);
      const hashAdmin = await bcrypt.hash('admin123', salt);
      const hashUser = await bcrypt.hash('user123', salt);

      await conn.execute(
        `INSERT INTO empleado (nombre, correo, contrasena, rol) VALUES (:1, :2, :3, :4)`,
        ['Administrador', 'admin@tienda.com', hashAdmin, 'ADMIN']
      );
      await conn.execute(
        `INSERT INTO empleado (nombre, correo, contrasena, rol) VALUES (:1, :2, :3, :4)`,
        ['Empleado Juan', 'juan@tienda.com', hashUser, 'USER']
      );

      // Insertar Productos semilla
      const productosDemo = [
        ['PROD-001', 'Arroz Blanco 1kg', 2.50, 3.80, 50, 10, 1],
        ['PROD-002', 'Aceite Vegetal 1L', 4.00, 5.50, 4, 10, 1],
        ['PROD-003', 'Leche Entera 1L', 1.10, 1.60, 30, 8, 2],
        ['PROD-004', 'Azúcar Blanca 1kg', 1.80, 2.70, 3, 12, 1],
        ['PROD-005', 'Detergente en Polvo 500g', 2.00, 3.20, 25, 5, 3],
        ['PROD-006', 'Gaseosa Cola 2.5L', 2.80, 4.20, 18, 6, 4]
      ];

      for (const p of productosDemo) {
        await conn.execute(
          `INSERT INTO producto (codigo, nombre, precio_compra, precio_venta, stock_actual, stock_minimo, id_categoria)
           VALUES (:1, :2, :3, :4, :5, :6, :7)`,
          p
        );
      }
      console.log('Datos semilla cargados correctamente.');
    }
  } catch (err) {
    console.error('Error al inicializar la base de datos:', err);
  } finally {
    if (conn) {
      await conn.close();
    }
  }
}

if (require.main === module) {
  initDB();
}

module.exports = initDB;
